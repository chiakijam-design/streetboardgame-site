// Generates src/generated/library-catalog.js from the built-in Japanese question cards.
// The crawlable /challenge/library catalog is rendered from this file by the Worker.
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import vm from 'node:vm';

export async function loadBuiltInJapaneseCards(root = new URL('..', import.meta.url)) {
  return loadBuiltInCards(root, 'prototype_common_data.js', 'COMMON_QUESTION_CARDS');
}

export async function loadBuiltInEnglishCards(root = new URL('..', import.meta.url)) {
  return loadBuiltInCards(root, 'prototype_english_common_data.js', 'ENGLISH_COMMON_QUESTION_CARDS');
}

async function loadBuiltInCards(root, file, key) {
  const source = await readFile(new URL(file, root), 'utf8');
  const sandbox = { window: {} };
  vm.runInNewContext(source, sandbox, { timeout: 1000 });
  const cards = sandbox.window[key];
  if (!Array.isArray(cards) || !cards.length) throw new Error(key + ' not found');
  return cards.map((card) => ({
    id: String(card.id),
    category: String(card.category),
    title: String(card.title),
    choices: card.choices.map(String),
  }));
}

export function libraryCatalogModule(cards, englishCards) {
  const categories = [];
  const byCategory = new Map();
  for (const card of cards) {
    if (!byCategory.has(card.category)) {
      byCategory.set(card.category, []);
      categories.push(card.category);
    }
    byCategory.get(card.category).push({ id: card.id, title: card.title, choices: card.choices });
  }
  const data = categories.map((name) => ({ name, questions: byCategory.get(name) }));
  return '// Generated by tools/build-library-catalog.mjs from prototype_common_data.js. Do not edit by hand.\n'
    + `export const LIBRARY_CATALOG = Object.freeze(${JSON.stringify(data, null, 1)});\n`
    + `export const ENGLISH_LIBRARY_CARDS = Object.freeze(${JSON.stringify(englishCards, null, 1)});\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [cards, englishCards] = await Promise.all([loadBuiltInJapaneseCards(), loadBuiltInEnglishCards()]);
  await writeFile(new URL('../src/generated/library-catalog.js', import.meta.url), libraryCatalogModule(cards, englishCards));
  console.log(`library catalog: ${cards.length} questions`);
}
