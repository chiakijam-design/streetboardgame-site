// Generates src/generated/library-catalog.js from the built-in Japanese question cards.
// The crawlable /challenge/library catalog is rendered from this file by the Worker.
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

export async function loadBuiltInJapaneseCards(root = new URL('..', import.meta.url)) {
  const source = await readFile(new URL('prototype_common_data.js', root), 'utf8');
  const sandbox = { window: {} };
  vm.runInNewContext(source, sandbox, { timeout: 1000 });
  const cards = sandbox.window.COMMON_QUESTION_CARDS;
  if (!Array.isArray(cards) || !cards.length) throw new Error('COMMON_QUESTION_CARDS not found');
  return cards.map((card) => ({
    id: String(card.id),
    category: String(card.category),
    title: String(card.title),
    choices: card.choices.map(String),
  }));
}

export function libraryCatalogModule(cards) {
  const categories = [];
  const byCategory = new Map();
  for (const card of cards) {
    if (!byCategory.has(card.category)) {
      byCategory.set(card.category, []);
      categories.push(card.category);
    }
    byCategory.get(card.category).push({ id: card.id, title: card.title, choices: card.choices });
  }
  const data = categories.map((name) => ({ name, questions: byCategory.get(name) }));
  return '// Generated by tools/build-library-catalog.mjs from prototype_common_data.js. Do not edit by hand.\n'
    + `export const LIBRARY_CATALOG = Object.freeze(${JSON.stringify(data, null, 1)});\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const cards = await loadBuiltInJapaneseCards();
  await writeFile(new URL('../src/generated/library-catalog.js', import.meta.url), libraryCatalogModule(cards));
  console.log(`library catalog: ${cards.length} questions`);
}
