// Generates src/generated/pack-questions.js: the questions shown on the
// crawlable 10-question pack pages (/challenge/library/<pack>) in the search
// languages. Japanese uses the built-in Japanese cards; English uses the
// curated English cards, and Spanish / Portuguese use the reviewed catalog
// translations of those English cards (the same text the quiz shows).
import { readFile, writeFile } from 'node:fs/promises';
import { loadBuiltInEnglishCards, loadBuiltInJapaneseCards } from './build-library-catalog.mjs';
import { questionPacks } from '../src/challenge/packs.js';

export const PACK_PAGE_LOCALES = Object.freeze(['ja', 'en', 'es', 'pt']);

async function loadTranslator(root, locale) {
  const data = JSON.parse(await readFile(new URL(`locale-assets/${locale}.json`, root), 'utf8'));
  const bySource = new Map(data.entries.map((entry) => [entry.source, data.catalog.messages[entry.id]]));
  return (text) => {
    const translated = bySource.get(text);
    if (typeof translated !== 'string' || !translated.trim()) throw new Error(`${locale}: missing translation for "${text}"`);
    return translated;
  };
}

export async function packQuestionData(root = new URL('..', import.meta.url)) {
  // 2026-11-21 (Codex review #15): keep the question ID so public pages can drop hidden questions.
  const japanese = new Map((await loadBuiltInJapaneseCards(root)).map((card) => [card.id, { id: String(card.id), title: card.title, choices: card.choices }]));
  const english = new Map((await loadBuiltInEnglishCards(root)).map(({ id, title, choices }) => [id, { id, title, choices }]));
  const translators = { es: await loadTranslator(root, 'es'), pt: await loadTranslator(root, 'pt') };
  const englishPacks = new Map(questionPacks(true).map((pack) => [pack.slug, pack]));
  const data = {};
  for (const pack of questionPacks(false)) {
    // Packs can also hold operator-added questions from the database; the
    // page lists the built-in ones, up to ten.
    const ja = pack.questionIds.map((id) => japanese.get(id)).filter(Boolean).slice(0, 10);
    const en = englishPacks.get(pack.slug).questionIds.map((id) => english.get(id)).filter(Boolean).slice(0, 10);
    const translate = (locale) => en.map((card) => ({ id: card.id, title: translators[locale](card.title), choices: card.choices.map(translators[locale]) }));
    data[pack.slug] = { ja, en, es: translate('es'), pt: translate('pt') };
  }
  return data;
}

export function packQuestionModule(data) {
  return '// Generated by tools/build-pack-questions.mjs. Do not edit by hand.\n'
    + `export const PACK_QUESTIONS = Object.freeze(${JSON.stringify(data, null, 1)});\n`;
}

if (import.meta.url === new URL(`file:///${process.argv[1].replace(/\\/g, '/').replace(/^\//, '')}`).href) {
  const data = await packQuestionData();
  await writeFile(new URL('../src/generated/pack-questions.js', import.meta.url), packQuestionModule(data));
  console.log(`pack questions: ${Object.keys(data).length} packs`);
}
