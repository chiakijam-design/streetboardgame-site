function addSource(prefix, sourceName, sourceUrl, groups) {
  for (const [category, rows] of groups) {
    for (const row of rows) {
      if (row.length !== 6) {
        throw new Error(`${prefix}/${category} must contain a title and five choices: ${row[0]}`);
      }
      const globalIndex = candidates.length + 201;
      const sourceIndex = (sourceIndexes.get(prefix) || 100) + 1;
      sourceIndexes.set(prefix, sourceIndex);
      candidates.push({
        id: `HLD${String(globalIndex).padStart(3, '0')}`,
        sourceRef: `${prefix}-${String(sourceIndex).padStart(3, '0')}`,
        sourceName,
        sourceUrl,
        category,
        title: row[0],
        choices: row.slice(1),
      });
    }
  }
}

